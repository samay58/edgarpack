"""End-to-end integration test for the pre-IPO / S-1 user journey.

Covers the demo flow without network access:

  1. universe.toml with a name-only pre-IPO filer loads without errors.
  2. form_counts emits the registration sentinel, not periodic forms.
  3. Planner expands the sentinel across the registration family and
     produces plan items for every form actually available.
  4. A built pack (simulated via fixtures) exposes S-1 metrics via the
     extract_s1_metrics_from_pack aggregator.
  5. The registration timeline renders a consecutive-pair redline with
     ranked changed sections.

If any step regresses, this single test catches it before merge.
"""

